//! Binary PLY writer for triangle meshes with normals and vertex colours.
//!
//! Layout: `element vertex` with `x y z` (f32), `nx ny nz` (f32) and
//! `red green blue` (u8), followed by `element face` with
//! `property list uchar int vertex_indices`. This is the format MeshLab,
//! CloudCompare, Blender and Open3D open without conversion.

use std::error::Error;
use std::fs::File;
use std::io::{BufWriter, Write};
use std::path::Path;

use kornia_algebra::Vec3F64;

use crate::mesh::Mesh;

/// Write `mesh` with per-vertex normals and colours.
///
/// # Errors
///
/// Returns an error if the file cannot be created or written, or if the
/// attribute arrays do not match the vertex count.
pub fn write_mesh_ply(
    path: &Path,
    mesh: &Mesh,
    normals: &[Vec3F64],
    colors: &[[u8; 3]],
) -> Result<(), Box<dyn Error>> {
    if normals.len() != mesh.vertex_count() || colors.len() != mesh.vertex_count() {
        return Err(format!(
            "attribute length mismatch: {} vertices, {} normals, {} colours",
            mesh.vertex_count(),
            normals.len(),
            colors.len()
        )
        .into());
    }

    let mut w = BufWriter::new(File::create(path)?);
    writeln!(w, "ply")?;
    writeln!(w, "format binary_little_endian 1.0")?;
    writeln!(w, "comment generated by sfm2mesh")?;
    writeln!(w, "element vertex {}", mesh.vertex_count())?;
    for p in ["x", "y", "z", "nx", "ny", "nz"] {
        writeln!(w, "property float {p}")?;
    }
    for p in ["red", "green", "blue"] {
        writeln!(w, "property uchar {p}")?;
    }
    writeln!(w, "element face {}", mesh.face_count())?;
    writeln!(w, "property list uchar int vertex_indices")?;
    writeln!(w, "end_header")?;

    for (p, (n, c)) in mesh.positions.iter().zip(normals.iter().zip(colors)) {
        for v in [p.x, p.y, p.z, n.x, n.y, n.z] {
            w.write_all(&(v as f32).to_le_bytes())?;
        }
        w.write_all(c)?;
    }
    for f in &mesh.faces {
        w.write_all(&[3u8])?;
        for v in f {
            w.write_all(&(*v as i32).to_le_bytes())?;
        }
    }
    w.flush()?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::Read;

    #[test]
    fn writes_a_valid_header_and_payload_sizes() {
        let mesh = Mesh {
            positions: vec![
                Vec3F64::new(0.0, 0.0, 0.0),
                Vec3F64::new(1.0, 0.0, 0.0),
                Vec3F64::new(0.0, 1.0, 0.0),
            ],
            faces: vec![[0, 1, 2]],
        };
        let normals = vec![Vec3F64::new(0.0, 0.0, 1.0); 3];
        let colors = vec![[10, 20, 30]; 3];

        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("mesh.ply");
        write_mesh_ply(&path, &mesh, &normals, &colors).unwrap();

        let mut bytes = Vec::new();
        File::open(&path).unwrap().read_to_end(&mut bytes).unwrap();
        let header_end = bytes
            .windows(b"end_header\n".len())
            .position(|w| w == b"end_header\n")
            .expect("header terminator")
            + b"end_header\n".len();
        let header = std::str::from_utf8(&bytes[..header_end]).unwrap();
        assert!(header.contains("element vertex 3"));
        assert!(header.contains("element face 1"));
        assert!(header.contains("property list uchar int vertex_indices"));

        // 3 vertices * 27 bytes + 1 face * 13 bytes.
        assert_eq!(bytes.len() - header_end, 3 * 27 + 13);
    }

    #[test]
    fn rejects_mismatched_attributes() {
        let mesh = Mesh {
            positions: vec![Vec3F64::ZERO],
            faces: vec![],
        };
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("bad.ply");
        assert!(write_mesh_ply(&path, &mesh, &[], &[]).is_err());
    }
}
